"""Launch file transpiler for NOS.

Converts NOS launch declarations to ROS2 Python launch files
with full support for groups, containers, and event handling.
"""

import json
import keyword
import re
from typing import Dict, Any, List, Optional, Set

from .generator import CodeGenerator, GenerationOutput
from .naming import (
    launch_module_name, node_module_name, ros_package_name, sanitize_package_name,
)
from ..ast import nodes
from ..semantic import SymbolTable


class LaunchTranspiler(CodeGenerator):
    """Transpiles NOS launch declarations to ROS2 Python launch files.

    Generates standard ROS2 launch files that are fully compatible
    with the ROS2 launch system.
    """

    def __init__(self, options: Optional[Dict[str, Any]] = None):
        super().__init__(options)
        self.launch_counter = 0
        self.package_name = "nos_generated"
        self._arg_names: Set[str] = set()
        # node/component type name -> ROS package that provides it
        self._type_packages: Dict[str, str] = {}

    def _reserved_keywords(self) -> set:
        return set(keyword.kwlist)

    def generate(self, ast: nodes.ASTNode, symbol_table: SymbolTable) -> GenerationOutput:
        """Generate launch files from AST."""
        self.output = GenerationOutput()
        self.package_name = ros_package_name(ast)
        self._type_packages = {}

        if isinstance(ast, nodes.File):
            self._collect_type_packages(ast)
            for decl in ast.declarations:
                if isinstance(decl, nodes.LaunchDecl):
                    self._transpile_launch(decl)
        elif isinstance(ast, nodes.LaunchDecl):
            self._transpile_launch(ast)

        return self.output

    def _collect_type_packages(self, ast: nodes.File) -> None:
        """Map node types to the ROS package that provides them.

        Nodes declared in this file live in this file's package.  A node from
        another package is brought in with ``import other_pkg::NodeType``.
        """
        for imp in ast.imports:
            parts = imp.qualified_name.split("::")
            if len(parts) >= 2:
                local_name = imp.alias or parts[-1]
                self._type_packages[local_name] = sanitize_package_name(parts[0])

    def _package_for(self, type_name: str) -> str:
        return self._type_packages.get(type_name, self.package_name)

    def _transpile_launch(self, launch: nodes.LaunchDecl) -> None:
        """Transpile a single launch declaration."""
        self.launch_counter += 1
        self._arg_names = {arg.name for arg in launch.arguments}

        launch_func = self._generate_launch_function(launch)
        imports = self._generate_launch_imports(launch_func)

        content = f'''# AUTO-GENERATED by NOS Launch Transpiler
# Source: {launch.location}
# Launch: {launch.name}

{imports}

{launch_func}
'''

        self.output.add_file(f"{launch_module_name(launch.name)}.py", content)

    def _generate_launch_imports(self, body: str) -> str:
        """Generate import statements for the names the launch file body uses."""
        candidates = [
            ("launch", "LaunchDescription"),
            ("launch.actions", "DeclareLaunchArgument"),
            ("launch.actions", "GroupAction"),
            ("launch.actions", "IncludeLaunchDescription"),
            ("launch.conditions", "IfCondition"),
            ("launch.conditions", "UnlessCondition"),
            ("launch.substitutions", "LaunchConfiguration"),
            ("launch.substitutions", "TextSubstitution"),
            ("launch.substitutions", "PathJoinSubstitution"),
            ("launch.substitutions", "Command"),
            ("launch.substitutions", "PythonExpression"),
            ("launch.substitutions", "EnvironmentVariable"),
            ("launch.launch_description_sources", "PythonLaunchDescriptionSource"),
            ("launch_ros.actions", "Node"),
            ("launch_ros.actions", "ComposableNodeContainer"),
            ("launch_ros.actions", "PushRosNamespace"),
            ("launch_ros.descriptions", "ComposableNode"),
            ("launch_ros.substitutions", "FindPackageShare"),
        ]
        by_module: Dict[str, List[str]] = {}
        for module, name in candidates:
            if re.search(rf"(?<![\w.]){name}\b", body):
                by_module.setdefault(module, []).append(name)
        return "\n".join(f"from {module} import {', '.join(names)}"
                         for module, names in by_module.items())

    def _generate_launch_function(self, launch: nodes.LaunchDecl) -> str:
        """Generate the generate_launch_description function."""
        lines = ["def generate_launch_description():"]

        lines.append("    actions = []")
        lines.append("")

        # Arguments are declared first so overrides from the CLI take effect.
        if launch.arguments:
            lines.append("    # Launch arguments")
            for arg in launch.arguments:
                lines.extend(self._generate_argument_declaration(arg))
                lines.append(f"    actions.append(declare_{arg.name})")
            lines.append("")
            # LaunchConfiguration handles, only for arguments the body refers to
            body_text = self._launch_body_text(launch)
            used = [arg for arg in launch.arguments
                    if re.search(rf"(?<![\w'\"]){re.escape(self._escape_identifier(arg.name))}\b(?!\s*=[^=])",
                                 body_text)]
            for arg in used:
                lines.append(
                    f"    {self._escape_identifier(arg.name)} = LaunchConfiguration('{arg.name}')"
                )
            if used:
                lines.append("")

        for group in launch.groups:
            lines.append(f"    {self._generate_group_action(group)}")
            lines.append("    actions.append(group_action)")
            lines.append("")

        for container in launch.containers:
            lines.append(f"    {self._generate_container_action(container)}")
            lines.append("    actions.append(container_action)")
            lines.append("")

        for include in launch.includes:
            lines.append(f"    {self._generate_include_action(include)}")
            lines.append("    actions.append(include_action)")
            lines.append("")

        if launch.lifecycle_manager:
            lines.append(f"    {self._generate_lifecycle_manager(launch.lifecycle_manager)}")
            lines.append("    actions.append(lifecycle_manager)")
            lines.append("")

        lines.append("    return LaunchDescription(actions)")

        return "\n".join(lines)

    def _launch_body_text(self, launch: nodes.LaunchDecl) -> str:
        """Generated text of everything that may reference an argument by name."""
        parts = [self._generate_group_action(g) for g in launch.groups]
        parts += [self._generate_container_action(c) for c in launch.containers]
        parts += [self._generate_include_action(i) for i in launch.includes]
        return "\n".join(parts)

    def _launch_value(self, expr: Optional[nodes.Expression]) -> str:
        """Python source for a value that ROS launch accepts as a string/substitution."""
        if isinstance(expr, nodes.LiteralExpression):
            if expr.literal_type == "string":
                return json.dumps(expr.value)
            if expr.literal_type == "bool":
                return json.dumps("true" if expr.value else "false")
            return json.dumps(str(expr.value))
        return self._expression_to_python(expr)

    def _generate_argument_declaration(self, arg: nodes.ArgumentDecl) -> List[str]:
        """Generate a DeclareLaunchArgument statement."""
        description = ""
        for constraint in arg.constraints:
            if constraint.name == "description" and constraint.arguments:
                description = self._launch_value(constraint.arguments[0])
        description = description or '""'

        lines = [f"    declare_{arg.name} = DeclareLaunchArgument(", f"        '{arg.name}',"]
        if arg.default_value is not None:
            lines.append(f"        default_value={self._launch_value(arg.default_value)},")
        lines.append(f"        description={description},")
        lines.append("    )")
        return lines

    def _generate_group_action(self, group: nodes.GroupDecl) -> str:
        """Generate GroupAction for a node group."""
        namespace = self._launch_value(group.namespace)
        lines = ["group_action = GroupAction(["]
        lines.append(f"        PushRosNamespace({namespace}),")

        for node in group.nodes:
            lines.append(f"        {self._generate_node_launch(node)},")

        lines.append("    ])")
        return "\n".join(lines)

    def _generate_node_launch(self, node: nodes.NodeInstance) -> str:
        """Generate Node action for launch."""
        args = [
            f"package='{self._package_for(node.node_type)}'",
            f"executable='{node_module_name(node.node_type)}'",
            f"name='{node.name}'",
        ]

        if node.parameters:
            pairs = ", ".join(
                f"'{key}': {self._expression_to_python(value)}"
                for key, value in node.parameters.items()
            )
            args.append(f"parameters=[{{{pairs}}}]")

        if node.remaps:
            pairs = ", ".join(f"('{src}', '{dst}')" for src, dst in node.remaps.items())
            args.append(f"remappings=[{pairs}]")

        if node.condition:
            args.append(f"condition=IfCondition({self._expression_to_python(node.condition)})")

        body = ",\n            ".join(args)
        return f"Node(\n            {body}\n        )"

    def _generate_container_action(self, container: nodes.ContainerDecl) -> str:
        """Generate ComposableNodeContainer action."""
        container_name = self._launch_value(container.container_name)

        components = []
        for comp in container.components:
            components.append(
                f"ComposableNode(\n"
                f"                package='{self._package_for(comp.component_type)}',\n"
                f"                plugin='{comp.component_type}',\n"
                f"                name='{comp.name}'\n"
                f"            )"
            )

        components_str = ",\n            ".join(components)

        return f'''container_action = ComposableNodeContainer(
        name={container_name},
        namespace='',
        package='rclcpp_components',
        executable='component_container',
        composable_node_descriptions=[
            {components_str}
        ]
    )'''

    def _generate_include_action(self, include: nodes.IncludeDecl) -> str:
        """Generate IncludeLaunchDescription action."""
        target = include.target
        if isinstance(target, nodes.IdentifierExpression):
            # ``include Other { }`` refers to another launch declaration in this package.
            source = (f"[FindPackageShare('{self.package_name}'), '/launch/', "
                      f"{json.dumps(launch_module_name(target.name) + '.py')}]")
        elif isinstance(target, str) and target.startswith("/"):
            source = json.dumps(target)
        else:
            source = (f"[FindPackageShare('{self.package_name}'), '/launch/', "
                      f"{json.dumps(str(target))}]")

        lines = [
            "include_action = IncludeLaunchDescription(",
            f"        PythonLaunchDescriptionSource({source})",
        ]
        if include.arguments:
            pairs = ", ".join(
                f"'{key}': {self._launch_value(value)}"
                for key, value in include.arguments.items()
            )
            lines[-1] += ","
            lines.append(f"        launch_arguments={{{pairs}}}.items()")
        lines.append("    )")
        return "\n".join(lines)

    def _generate_lifecycle_manager(self, manager: nodes.LifecycleManagerDecl) -> str:
        """Generate a lifecycle manager (nav2's lifecycle_manager) for the managed nodes."""
        managed = ", ".join(f"'{n}'" for n in manager.managed_nodes)

        return f'''lifecycle_manager = Node(
        package='nav2_lifecycle_manager',
        executable='lifecycle_manager',
        name='{manager.name}',
        parameters=[{{'node_names': [{managed}], 'autostart': True}}]
    )'''
