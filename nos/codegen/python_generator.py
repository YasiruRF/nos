"""Python code generator for NOS.

Generates ROS2 Python nodes from NOS AST.
"""

import io
import keyword
import logging
import re
import textwrap
import tokenize
from typing import Any, Dict, List, Optional, Set

from ..ast import nodes
from ..security import SecurityError, validate_callback_code
from ..semantic import SymbolTable, SymbolType
from .generator import CodeGenerator, GenerationOutput
from .naming import camel_to_snake, node_module_name

# Configure audit logging
logger = logging.getLogger(__name__)


class PythonGenerator(CodeGenerator):
    """Generates Python ROS2 code from NOS AST."""

    def __init__(self, options: Optional[Dict[str, Any]] = None):
        super().__init__(options)
        self.target = "python"
        self.package_name: Optional[str] = None
        self.symbol_table: Optional[SymbolTable] = None
        self._type_aliases: Dict[tuple, str] = {}

    def _reserved_keywords(self) -> set:
        """Python reserved keywords."""
        return set(keyword.kwlist)

    def generate(self, ast: nodes.ASTNode, symbol_table: SymbolTable) -> GenerationOutput:
        """Generate Python code from AST."""
        self.output = GenerationOutput()
        self.symbol_table = symbol_table

        if isinstance(ast, nodes.File):
            if ast.package:
                self.package_name = ast.package.name

            for decl in ast.declarations:
                if isinstance(decl, nodes.NodeDecl):
                    self._generate_node(decl)
        elif isinstance(ast, nodes.NodeDecl):
            self._generate_node(ast)

        return self.output

    def _is_lifecycle(self, node: nodes.NodeDecl) -> bool:
        return bool(node.lifecycle and node.lifecycle.is_managed)

    def _generate_node(self, node: nodes.NodeDecl) -> None:
        """Generate Python code for a node."""
        class_name = node.name
        base_class = "NOSLifecycleNode" if self._is_lifecycle(node) else "NOSNode"
        self._compute_type_aliases(node)

        class_def = self._generate_node_class(node, class_name, base_class)
        main = self._generate_main_function(node, class_name)
        imports = self._generate_node_imports(node, base_class, class_def + "\n" + main)

        content = f"""# AUTO-GENERATED by NOS - Do not edit manually
# Source: {node.location}

{imports}

{class_def}

{main}
"""

        self.output.add_file(f"{node_module_name(class_name)}.py", content)

    def _is_client(self, decl) -> bool:
        return any(c.name == "client" for c in decl.constraints)

    def _is_reentrant(self, decl) -> bool:
        return any(c.name == "reentrant" for c in decl.constraints)

    def _has_reentrant(self, node: nodes.NodeDecl) -> bool:
        return any(
            self._is_reentrant(decl)
            for decl in (*node.subscriptions, *node.publications, *node.services, *node.actions)
        )

    def _uses(self, code: str, name: str) -> bool:
        return re.search(rf"(?<![\w.]){re.escape(name)}\b", code) is not None

    def _interface_types(self, node: nodes.NodeDecl) -> List[tuple]:
        """Every (package, kind, name) interface type the node refers to."""
        found = []

        def add(type_node: Optional[nodes.Type], kind: str) -> None:
            if isinstance(type_node, nodes.ListType):
                add(type_node.element_type, kind)
            elif isinstance(type_node, nodes.QualifiedType) and type_node.package:
                found.append((type_node.package, type_node.kind or kind, type_node.name))

        for sub in node.subscriptions:
            add(sub.message_type, "msg")
        for pub in node.publications:
            add(pub.message_type, "msg")
        for svc in node.services:
            add(svc.service_type, "srv")
        for act in node.actions:
            add(act.action_type, "action")
        for cb in node.callbacks:
            for param in cb.parameters:
                add(param.type, "msg")
        return found

    def _compute_type_aliases(self, node: nodes.NodeDecl) -> None:
        """Alias interface types whose short names clash (``a::Thing`` vs ``b::Thing``)."""
        by_name: Dict[str, Set[tuple]] = {}
        for package, kind, name in self._interface_types(node):
            by_name.setdefault(name, set()).add((package, kind))
        self._type_aliases = {
            (package, name): f"{package}_{name}"
            for name, origins in by_name.items()
            if len(origins) > 1
            for package, _kind in origins
        }

    def _type_name(self, type_node: nodes.QualifiedType) -> str:
        """Python name for an interface type (aliased if its short name is ambiguous)."""
        return self._type_aliases.get((type_node.package, type_node.name), type_node.name)

    def _interface_imports(self, node: nodes.NodeDecl) -> List[str]:
        """Explicit ``from pkg.kind import Type`` lines for every interface the node uses."""
        wanted: Dict[tuple, Set[str]] = {}
        for package, kind, name in self._interface_types(node):
            alias = self._type_aliases.get((package, name))
            wanted.setdefault((package, kind), set()).add(f"{name} as {alias}" if alias else name)

        return [f"from {pkg}.{kind} import {', '.join(sorted(names))}" for (pkg, kind), names in sorted(wanted.items())]

    def _generate_node_imports(self, node: nodes.NodeDecl, base_class: str, body: str) -> str:
        """Generate import statements for a node.

        ``body`` is the generated class and entry point; imports for helper
        names are emitted only when the body actually references them.
        """
        imports = ["import rclpy"]

        typing_names = [n for n in ("Any", "List") if self._uses(body, n)]
        if typing_names:
            imports.append(f"from typing import {', '.join(typing_names)}")

        if self._uses(body, "Duration"):
            imports.append("from rclpy.duration import Duration")
        if self._uses(body, "Time"):
            imports.append("from rclpy.time import Time")

        range_types = [n for n in ("FloatingPointRange", "IntegerRange") if self._uses(body, n)]
        if self._uses(body, "ParameterDescriptor"):
            imports.append("from rcl_interfaces.msg import " + ", ".join(["ParameterDescriptor"] + range_types))

        runtime = [base_class] + (["create_qos_profile"] if self._uses(body, "create_qos_profile") else [])
        imports.append(f"from nos.runtime import {', '.join(runtime)}")

        if self._uses(body, "ReentrantCallbackGroup"):
            imports.append("from rclpy.callback_groups import ReentrantCallbackGroup")

        executors = [n for n in ("MultiThreadedExecutor", "SingleThreadedExecutor") if self._uses(body, n)]
        if executors:
            imports.append(f"from rclpy.executors import {', '.join(executors)}")

        imports.extend(self._interface_imports(node))

        if self._uses(body, "ActionClient"):
            imports.append("from rclpy.action import ActionClient")
        action_server = [n for n in ("ActionServer", "GoalResponse", "CancelResponse") if self._uses(body, n)]
        if action_server:
            imports.append(f"from rclpy.action import {', '.join(action_server)}")

        return "\n".join(imports)

    def _generate_node_class(self, node: nodes.NodeDecl, class_name: str, base_class: str) -> str:
        """Generate node class definition."""
        node_name = camel_to_snake(class_name)

        # Generate docstring
        docstring = f'    """Auto-generated base class for {class_name} node."""'

        # Generate __init__ method
        init_method = self._generate_init_method(node, node_name)

        # Generate parameter properties
        param_properties = self._generate_parameter_properties(node)

        # Generate parameter declaration method
        param_method = self._generate_declare_parameters_method(node)

        # Generate communication setup method
        comm_method = self._generate_setup_communications_method(node)

        # Generate callback wrappers
        callbacks = self._generate_callbacks(node)

        # Generate lifecycle methods if managed
        lifecycle_methods = ""
        if self._is_lifecycle(node):
            lifecycle_methods = self._generate_teardown_method(node) + "\n\n" + self._generate_lifecycle_methods(node)

        return f"""class {class_name}Base({base_class}):
{docstring}

{init_method}

{param_properties}

{param_method}

{comm_method}

{callbacks}

{lifecycle_methods}
"""

    def _generate_parameter_properties(self, node: nodes.NodeDecl) -> str:
        """Generate property accessors for parameters."""
        lines = []

        def prop(attr: str, ros_name: str) -> None:
            lines.append("    @property")
            lines.append(f"    def {self._escape_identifier(attr)}(self):")
            lines.append(f"        return self.get_parameter('{ros_name}').value")
            lines.append("")

        for param in node.parameters:
            if isinstance(param.type, nodes.StructType):
                # Flattened properties for struct fields, plus a dict for the whole struct
                for field in param.type.fields:
                    prop(f"{param.name}_{field.name}", f"{param.name}.{field.name}")
                items = ", ".join(
                    f"'{f.name}': self.{self._escape_identifier(param.name + '_' + f.name)}" for f in param.type.fields
                )
                lines.append("    @property")
                lines.append(f"    def {self._escape_identifier(param.name)}(self):")
                lines.append(f"        return {{{items}}}")
                lines.append("")
            else:
                prop(param.name, param.name)

        return "\n".join(lines)

    def _generate_init_method(self, node: nodes.NodeDecl, node_name: str) -> str:
        """Generate __init__ method."""
        lines = [
            f"    def __init__(self, node_name: str = '{node_name}'):",
            f"        super().__init__(node_name)",
            "",
            "        # Parameter declarations",
            "        self._declare_nos_parameters()",
            "",
        ]
        if not self._is_lifecycle(node):
            # Lifecycle nodes create their communications in on_configure.
            lines.extend(
                [
                    "        # Setup communications",
                    "        self._setup_communications()",
                    "",
                ]
            )
        lines.extend(
            [
                "        # Call user initialization",
                "        self.on_init()",
            ]
        )

        return "\n".join(lines)

    def _generate_declare_parameters_method(self, node: nodes.NodeDecl) -> str:
        """Generate parameter declaration method."""
        lines = ["    def _declare_nos_parameters(self):"]

        if not node.parameters:
            lines.append("        pass")
            return "\n".join(lines)

        for param in node.parameters:
            if isinstance(param.type, nodes.StructType):
                # Flatten struct parameters for ROS2
                for field in param.type.fields:
                    param_name = f"{param.name}.{field.name}"
                    default_value = "None"
                    initializer = param.default_value
                    if isinstance(initializer, nodes.StructInitializerExpression) and field.name in initializer.fields:
                        default_value = self._expression_to_python(initializer.fields[field.name])
                    elif field.default_value is not None:
                        default_value = self._expression_to_python(field.default_value)

                    lines.append(f"        self.declare_parameter('{param_name}', {default_value})")
            else:
                param_name = param.name
                default_value = self._expression_to_python(param.default_value) if param.default_value else "None"

                descriptor = ""
                if param.constraints:
                    constraint_code = self._generate_parameter_constraints(param)
                    if constraint_code:
                        descriptor = f", descriptor={constraint_code}"

                lines.append(f"        self.declare_parameter('{param_name}', {default_value}{descriptor})")

        return "\n".join(lines)

    def _generate_parameter_constraints(self, param: nodes.ParameterDecl) -> str:
        """Generate parameter constraint descriptor."""
        descriptor_parts = []
        is_float = self._get_python_type(param.type) == "float"

        for constraint in param.constraints:
            if constraint.name == "description" and constraint.arguments:
                descriptor_parts.append(f"description={self._expression_to_python(constraint.arguments[0])}")
            elif constraint.name == "range" and len(constraint.arguments) >= 2:
                min_val = self._expression_to_python(constraint.arguments[0])
                max_val = self._expression_to_python(constraint.arguments[1])
                if is_float:
                    descriptor_parts.append(
                        f"floating_point_range=[FloatingPointRange("
                        f"from_value=float({min_val}), to_value=float({max_val}))]"
                    )
                else:
                    descriptor_parts.append(
                        f"integer_range=[IntegerRange(" f"from_value=int({min_val}), to_value=int({max_val}))]"
                    )

        if descriptor_parts:
            return f"ParameterDescriptor({', '.join(descriptor_parts)})"
        return ""

    def _generate_setup_communications_method(self, node: nodes.NodeDecl) -> str:
        """Generate communication setup method."""
        lines = ["    def _setup_communications(self):"]

        if not (node.subscriptions or node.publications or node.services or node.actions):
            lines.append("        pass")
            return "\n".join(lines)

        if self._has_reentrant(node):
            lines.append("        self._reentrant_group = ReentrantCallbackGroup()")

        # Generate subscriptions
        for sub in node.subscriptions:
            msg_type = self._type_name(sub.message_type)
            topic_expr = self._expression_to_python(sub.topic)
            callback_name = f"_on_{sub.name}_received"
            qos = self._generate_qos_config(sub.qos)

            cb_group = ""
            if self._is_reentrant(sub):
                cb_group = ", callback_group=self._reentrant_group"

            lines.extend(
                [
                    f"        self._{sub.name}_sub = self.create_subscription(",
                    f"            {msg_type}, {topic_expr}, self.{callback_name}, {qos}{cb_group}",
                    f"        )",
                ]
            )

        lines.append("")

        # Generate publishers (lifecycle nodes publish only while active)
        create_pub = "create_lifecycle_publisher" if self._is_lifecycle(node) else "create_publisher"
        for pub in node.publications:
            msg_type = self._type_name(pub.message_type)
            topic_expr = self._expression_to_python(pub.topic)
            qos = self._generate_qos_config(pub.qos)

            cb_group = ""
            if self._is_reentrant(pub):
                cb_group = ", callback_group=self._reentrant_group"

            lines.extend(
                [
                    f"        self.{self._escape_identifier(pub.name)} = self.{create_pub}(",
                    f"            {msg_type}, {topic_expr}, {qos}{cb_group}",
                    f"        )",
                ]
            )

        lines.append("")

        # Generate services (servers & clients)
        for svc in node.services:
            svc_type = self._type_name(svc.service_type)
            svc_name = self._expression_to_python(svc.service_name)

            cb_group = ""
            if self._is_reentrant(svc):
                cb_group = ", callback_group=self._reentrant_group"

            if self._is_client(svc):
                lines.extend(
                    [
                        f"        self.{self._escape_identifier(svc.name)} = self.create_client(",
                        f"            {svc_type}, {svc_name}{cb_group}",
                        f"        )",
                    ]
                )
            else:
                callback_name = f"_{svc.name}_callback"
                lines.extend(
                    [
                        f"        self._{svc.name}_srv = self.create_service(",
                        f"            {svc_type}, {svc_name}, self.{callback_name}{cb_group}",
                        f"        )",
                    ]
                )

        lines.append("")

        # Generate actions (servers & clients)
        for act in node.actions:
            action_type = self._type_name(act.action_type)
            action_name = f"'{act.name}'"

            cb_group = ""
            if self._is_reentrant(act):
                cb_group = ", callback_group=self._reentrant_group"

            if self._is_client(act):
                lines.extend(
                    [
                        f"        self.{self._escape_identifier(act.name)} = ActionClient(",
                        f"            self, {action_type}, {action_name}{cb_group}",
                        f"        )",
                    ]
                )
            else:
                user_implemented_events = {cb.event for cb in node.callbacks}

                goal_cb = ""
                if f"on_{act.name}_goal" in user_implemented_events or f"{act.name}_goal" in user_implemented_events:
                    goal_name = (
                        f"on_{act.name}_goal"
                        if f"on_{act.name}_goal" in user_implemented_events
                        else f"{act.name}_goal"
                    )
                    goal_cb = f", goal_callback=self.{goal_name}"

                cancel_cb = ""
                if (
                    f"on_{act.name}_cancel" in user_implemented_events
                    or f"{act.name}_cancel" in user_implemented_events
                ):
                    cancel_name = (
                        f"on_{act.name}_cancel"
                        if f"on_{act.name}_cancel" in user_implemented_events
                        else f"{act.name}_cancel"
                    )
                    cancel_cb = f", cancel_callback=self.{cancel_name}"

                callback_name = f"_on_{act.name}_execute"
                lines.extend(
                    [
                        f"        self._{act.name}_action_server = ActionServer(",
                        f"            self, {action_type}, {action_name},",
                        f"            execute_callback=self.{callback_name}{goal_cb}{cancel_cb}{cb_group}",
                        f"        )",
                    ]
                )

        return "\n".join(lines)

    def _generate_qos_config(self, qos: Optional[nodes.QoSConfig]) -> str:
        """Generate QoS configuration code."""
        if qos is None:
            return "10"

        args = []
        if qos.reliability:
            args.append(f"reliability='{qos.reliability}'")
        if qos.durability:
            args.append(f"durability='{qos.durability}'")
        if qos.history:
            args.append(f"history='{qos.history}'")
        if qos.depth is not None:
            args.append(f"depth={qos.depth}")

        return f"create_qos_profile({', '.join(args)})"

    def _generate_callbacks(self, node: nodes.NodeDecl) -> str:
        """Generate callback method wrappers with security validation."""
        callbacks = []
        security_errors = []

        # Get list of events that have user implementations
        user_implemented_events = {cb.event for cb in node.callbacks}

        # Generate subscription callbacks
        for sub in node.subscriptions:
            msg_type = self._type_name(sub.message_type)
            callback_name = f"{sub.name}_received"
            user_callback = callback_name
            if f"on_{callback_name}" in user_implemented_events:
                user_callback = f"on_{callback_name}"

            # Wrapper
            wrapper = f'''    def _on_{sub.name}_received(self, msg: {msg_type}):
        """Wrapper for {sub.name} subscription callback."""
        try:
            self.{user_callback}(msg)
        except Exception as e:
            self.get_logger().error(f"Error in {sub.name} callback: {{e}}")
'''
            callbacks.append(wrapper)

            # Default implementation if not provided by user
            if callback_name not in user_implemented_events and f"on_{callback_name}" not in user_implemented_events:
                default_impl = f'''
    def {callback_name}(self, msg: {msg_type}):
        """Default implementation for {sub.name} messages."""
        pass
'''
                callbacks.append(default_impl)

        # Generate service callbacks
        for svc in node.services:
            if self._is_client(svc):
                continue
            callback_name = f"{svc.name}_callback"
            user_callback_name = f"{svc.name}_request"
            user_callback = user_callback_name
            if f"on_{user_callback_name}" in user_implemented_events:
                user_callback = f"on_{user_callback_name}"

            # Wrapper
            wrapper = f'''    def _{callback_name}(self, request, response):
        """Wrapper for {svc.name} service callback."""
        try:
            return self.{user_callback}(request, response)
        except Exception as e:
            self.get_logger().error(f"Error in {svc.name} service: {{e}}")
            response.success = False
            return response
'''
            callbacks.append(wrapper)

            # Default implementation if not provided by user
            if (
                user_callback_name not in user_implemented_events
                and f"on_{user_callback_name}" not in user_implemented_events
            ):
                default_impl = f'''
    def {user_callback_name}(self, request, response):
        """Default implementation for {svc.name} requests."""
        response.success = True
        return response
'''
                callbacks.append(default_impl)

        # Generate action callbacks
        for act in node.actions:
            if self._is_client(act):
                continue
            action_type = self._type_name(act.action_type)
            callback_name = f"{act.name}_execute"
            user_callback = callback_name
            if f"on_{callback_name}" in user_implemented_events:
                user_callback = f"on_{callback_name}"

            # Wrapper
            wrapper = f'''    def _on_{act.name}_execute(self, goal_handle):
        """Wrapper for {act.name} action execute callback."""
        try:
            return self.{user_callback}(goal_handle)
        except Exception as e:
            self.get_logger().error(f"Error in {act.name} action execute callback: {{e}}")
            goal_handle.abort()
            return {action_type}.Result()
'''
            callbacks.append(wrapper)

            # Default implementation if not provided by user
            if callback_name not in user_implemented_events and f"on_{callback_name}" not in user_implemented_events:
                default_impl = f'''
    def {callback_name}(self, goal_handle):
        """Default implementation for {act.name} action execution."""
        goal_handle.succeed()
        return {action_type}.Result()
'''
                callbacks.append(default_impl)

        # Generate lifecycle callbacks with security validation
        for cb in node.callbacks:
            # Validate embedded Python code for security
            body = cb.body
            wrapped_body = None
            if body:
                # Clean up body for validation and generation
                # We strip leading/trailing newlines but KEEP leading spaces on the first line
                # so that textwrap.dedent can work correctly.
                cleaned_body = body.strip("\r\n")
                cleaned_body = self._dedent_code(cleaned_body)

                # Interpolate NOS parameters BEFORE validation
                # so that the code is valid Python syntax.
                cleaned_body = self._interpolate_nos_parameters(cleaned_body)

                validation_result = validate_callback_code(cleaned_body, strict=True)
                if not validation_result.is_safe:
                    security_errors.extend(validation_result.errors)
                    logger.warning(
                        f"Security validation failed for callback '{cb.event}': " f"{validation_result.errors}"
                    )
                    # Replace dangerous code with a safe error message
                    body = f"        # SECURITY ERROR: Callback code blocked due to security violations:\n"
                    body += "        # " + "\n        # ".join(validation_result.errors)
                    body += "\n        self.get_logger().error('Security validation failed for callback')"
                    body += "\n        pass"
                else:
                    # Use cleaned and interpolated body
                    body = cleaned_body

                    if validation_result.warnings:
                        # Prepend warnings as comments
                        body = f"# SECURITY WARNINGS:\n"
                        body += "# " + "\n# ".join(validation_result.warnings) + "\n" + body
                        # Log audit event
                        logger.info(
                            f"Callback '{cb.event}' passed security validation with warnings: "
                            f"{validation_result.warnings}"
                        )
                    else:
                        # Log successful validation
                        logger.info(f"Callback '{cb.event}' passed security validation")

                # Wrap validated code in try/except for runtime safety
                # Note: body already has interpolation applied here
                wrapped_body = self._wrap_code_in_try_except(body, cb.event)

            if cb.event == "on_init":
                if wrapped_body:
                    callback_body = wrapped_body
                else:
                    callback_body = "        pass"
                callback = f'''    def on_init(self):
        """User initialization callback."""
{callback_body}
'''
            elif cb.event == "on_shutdown":
                if wrapped_body:
                    callback_body = wrapped_body
                else:
                    callback_body = "        pass"
                # Lifecycle nodes already use on_shutdown(state) as the ROS transition hook.
                hook = "on_nos_shutdown" if self._is_lifecycle(node) else "on_shutdown"
                callback = f'''    def {hook}(self):
        """User shutdown callback."""
{callback_body}
'''
            else:
                method_params = ["self"]
                for p in cb.parameters:
                    method_params.append(f"{p.name}: {self._get_python_type(p.type)}")

                params_str = ", ".join(method_params)

                if wrapped_body:
                    callback_body = wrapped_body
                else:
                    callback_body = "        pass"
                callback = f'''    def {cb.event}({params_str}):
        """User callback: {cb.event}."""
{callback_body}
'''
            callbacks.append(callback)

        # Store security errors for later reporting
        if security_errors:
            self.output.security_errors.extend(security_errors)
            logger.error(f"Security errors found in callbacks: {security_errors}")

        # Log audit event for generated code
        logger.info(f"Generated {len(callbacks)} callbacks for node")

        return "\n".join(callbacks)

    def _string_continuation_lines(self, code: str) -> Optional[Set[int]]:
        """0-based indexes of lines that start inside a multi-line string literal.

        Returns None if the code cannot be tokenized.
        """
        protected: Set[int] = set()
        try:
            for tok in tokenize.generate_tokens(io.StringIO(code).readline):
                if tok.type in (tokenize.STRING, getattr(tokenize, "FSTRING_MIDDLE", -1)) and tok.end[0] > tok.start[0]:
                    protected.update(range(tok.start[0], tok.end[0]))  # rows are 1-based
        except (tokenize.TokenError, IndentationError, SyntaxError):
            return None
        return protected

    def _dedent_code(self, code: str) -> str:
        """Remove the common indentation, ignoring lines inside multi-line strings."""
        protected = self._string_continuation_lines(textwrap.dedent(code))
        if not protected:
            return textwrap.dedent(code)

        lines = code.split("\n")
        margins = [
            len(line) - len(line.lstrip()) for i, line in enumerate(lines) if line.strip() and i not in protected
        ]
        margin = min(margins, default=0)
        return "\n".join(line if i in protected else line[margin:] for i, line in enumerate(lines))

    def _indent_code(self, code: str, level: int) -> str:
        """Indent Python source without touching the contents of multi-line strings."""
        protected = self._string_continuation_lines(code)
        if protected is None:
            return self._indent(code, level)

        pad = "    " * level
        return "\n".join(
            line if (i in protected or not line.strip()) else pad + line for i, line in enumerate(code.split("\n"))
        )

    def _wrap_code_in_try_except(self, body: str, callback_name: str) -> str:
        """Wrap callback body in try/except for runtime safety.

        Args:
            body: The callback body code (should be pre-interpolated)
            callback_name: Name of the callback for error messages

        Returns:
            Wrapped code string
        """
        if not body or not body.strip():
            return "        pass"

        # Indent the body content
        # Level 3 (12 spaces) to be nested inside 'try:' which is at level 2 (8 spaces)
        indented_body = self._indent_code(body.strip(), 3)

        # Generate the wrapped code
        wrapped = f"""        try:
{indented_body}
        except Exception as e:
            self.get_logger().error(f"Error in {callback_name} callback: {{e}}")
            raise  # Re-raise to allow upstream handling"""

        return wrapped

    _INTERPOLATION = re.compile(r"\$\{([a-zA-Z0-9_\.]+)\}")

    def _interpolate_nos_parameters(self, body: str) -> str:
        """Replace NOS parameter interpolation ``${param}`` / ``${param.field}``.

        Outside string literals it becomes ``self.param`` / ``self.param_field``.
        Inside an f-string it becomes a replacement field (``{self.param}``),
        so ``f"rate ${rate}"`` works.  In a plain string it is left untouched.
        """

        def prop(path: str) -> str:
            return f"self.{self._escape_identifier(path.replace('.', '_'))}"

        out = []
        i, n = 0, len(body)
        while i < n:
            ch = body[i]

            if ch == "#":  # comment: copy to end of line
                end = body.find("\n", i)
                end = n if end == -1 else end
                out.append(body[i:end])
                i = end
                continue

            if ch in "\"'":
                # string literal; its prefix (f, r, b, ...) was already copied to `out`
                prefix = re.search(r"(?<![\w])([rRbBfFuU]{1,2})$", "".join(out[-3:]))
                is_f = bool(prefix and "f" in prefix.group(1).lower())
                quote = body[i : i + 3] if body[i : i + 3] in ('"""', "'''") else ch
                j = i + len(quote)
                chunk = [quote]
                while j < n and not body.startswith(quote, j):
                    if body[j] == "\\" and j + 1 < n:
                        chunk.append(body[j : j + 2])
                        j += 2
                        continue
                    match = self._INTERPOLATION.match(body, j)
                    if match and is_f:
                        chunk.append("{" + prop(match.group(1)) + "}")
                        j = match.end()
                        continue
                    chunk.append(body[j])
                    j += 1
                chunk.append(body[j : j + len(quote)])
                out.append("".join(chunk))
                i = j + len(quote)
                continue

            match = self._INTERPOLATION.match(body, i)
            if match:
                out.append(prop(match.group(1)))
                i = match.end()
                continue

            out.append(ch)
            i += 1

        return "".join(out)

    def _generate_lifecycle_methods(self, node: nodes.NodeDecl) -> str:
        """Generate the lifecycle hooks that need node-specific code.

        Everything else (activate/deactivate/shutdown) is inherited from
        ``NOSLifecycleNode``; the user's ``on_shutdown`` callback is generated
        as ``on_nos_shutdown`` so it cannot collide with the transition hook.
        """
        return '''    def on_configure(self, state):
        """Create publishers, subscriptions, services and actions."""
        self._setup_communications()
        return super().on_configure(state)

    def on_cleanup(self, state):
        """Destroy everything created in on_configure."""
        self._teardown_communications()
        return super().on_cleanup(state)
'''

    def _generate_teardown_method(self, node: nodes.NodeDecl) -> str:
        """Generate the method that destroys what _setup_communications created."""
        lines = ["    def _teardown_communications(self):"]
        body = []
        for sub in node.subscriptions:
            body.append(f"        self.destroy_subscription(self._{sub.name}_sub)")
        for pub in node.publications:
            body.append(f"        self.destroy_publisher(self.{self._escape_identifier(pub.name)})")
        for svc in node.services:
            name = self._escape_identifier(svc.name)
            if self._is_client(svc):
                body.append(f"        self.destroy_client(self.{name})")
            else:
                body.append(f"        self.destroy_service(self._{svc.name}_srv)")
        for act in node.actions:
            name = self._escape_identifier(act.name)
            if self._is_client(act):
                body.append(f"        self.{name}.destroy()")
            else:
                body.append(f"        self._{act.name}_action_server.destroy()")
        return "\n".join(lines + (body or ["        pass"]))

    def _generate_main_function(self, node: nodes.NodeDecl, class_name: str) -> str:
        """Generate main entry point."""
        executor = "MultiThreadedExecutor" if self._has_reentrant(node) else "SingleThreadedExecutor"
        shutdown_hook = "" if self._is_lifecycle(node) else "        node.on_shutdown()\n"
        return f"""def main(args=None):
    rclpy.init(args=args)
    node = {class_name}Base()
    executor = {executor}()
    executor.add_node(node)
    try:
        executor.spin()
    finally:
{shutdown_hook}        executor.shutdown()
        node.destroy_node()
        rclpy.shutdown()


if __name__ == '__main__':
    main()
"""

    def _get_python_type(self, type_node: Optional[nodes.Type]) -> str:
        """Convert NOS type to Python type annotation."""
        if type_node is None:
            return "Any"

        if isinstance(type_node, nodes.PrimitiveType):
            type_map = {
                "bool": "bool",
                "int": "int",
                "float": "float",
                "double": "float",
                "string": "str",
                "duration": "Duration",
                "time": "Time",
            }
            return type_map.get(type_node.kind.value, "Any")

        elif isinstance(type_node, nodes.QualifiedType):
            return self._type_name(type_node)

        elif isinstance(type_node, nodes.ListType):
            element = self._get_python_type(type_node.element_type)
            return f"List[{element}]"

        return "Any"
