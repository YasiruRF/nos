def package_dependencies(ast: Optional[nodes.ASTNode]) -> List[str]:
    """ROS packages a compiled file needs: ``depends:``, imports and interface packages."""
    found: List[str] = []

    def add(name: Optional[str]) -> None:
        if name and name not in found:
            found.append(name)

    def walk(value: Any) -> None:
        if isinstance(value, nodes.QualifiedType):
            add(value.package)
        elif isinstance(value, nodes.ASTNode):
            for item in vars(value).values():
                walk(item)
        elif isinstance(value, (list, tuple)):
            for item in value:
                walk(item)
        elif isinstance(value, dict):
            for item in value.values():
                walk(item)

    if isinstance(ast, nodes.File):
        if ast.package:
            for dep in ast.package.dependencies:
                add(dep)
        for imp in ast.imports:
            add(imp.qualified_name.split("::")[0])
        walk(ast.declarations)
    return found


class NOSSyntaxError(Exception):
    """Syntax error in NOS source.

    Attributes:
        errors: List of syntax error messages
    """

    def __init__(self, errors: List[str]):
        self.errors = errors
        super().__init__("\n".join(errors))


class NOSInternalError(Exception):
    """A bug in the compiler (as opposed to a mistake in the NOS source)."""


class NOSErrorListener(ErrorListener):
    """Custom error listener for ANTLR4 syntax errors."""

    def __init__(self, file_name: str = "<input>"):
        super().__init__()
        self.file_name = file_name
        self.errors: List[str] = []

    def syntaxError(self, recognizer, offendingSymbol, line, column, msg, e):
        self.errors.append(f"{self.file_name}:{line}:{column}: error: {msg}")


@dataclass
class CompilationResult:
    """Result of a compilation.

    Attributes:
        success: True if compilation succeeded
        files: Generated files (path -> content)
        errors: Compilation errors
        warnings: Compilation warnings
        ast: The parsed and validated AST
    """

    success: bool = False
    files: Dict[str, str] = field(default_factory=dict)
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    ast: Optional[nodes.ASTNode] = None
    package_name: str = "nos_generated"
    package_version: Optional[str] = None
    dependencies: List[str] = field(default_factory=list)

    @classmethod
    def merge(cls, results: List["CompilationResult"]) -> "CompilationResult":
        """Combine successful results that belong to one ROS package.

        The merged result carries every generated file, so the package
        scaffold (setup.py entry points, launch data files, package.xml) is
        written once for all inputs instead of once per input.
        """
        merged = cls(success=True)
        for result in results:
            if not merged.files:
                merged.package_name = result.package_name
                merged.ast = result.ast
            if merged.package_version is None:
                merged.package_version = result.package_version
            merged.warnings.extend(result.warnings)
            for dep in result.dependencies:
                if dep not in merged.dependencies:
                    merged.dependencies.append(dep)
            for name, content in result.files.items():
                if name in merged.files and merged.files[name] != content:
                    merged.success = False
                    merged.errors.append(f"error: '{name}' is generated by more than one input file")
                merged.files[name] = content
        return merged


class CompilerPipeline:
    """End-to-end NOS compilation pipeline.

    Orchestrates:
    1. Source file parsing (using ANTLR4)
    2. AST construction
    3. Semantic analysis
    4. Code generation

    Usage:
        >>> pipeline = CompilerPipeline()
        >>> result = pipeline.compile_file("input.node")
        >>> if result.success:
        ...     pipeline.write_outputs(result, "output_dir/")
        ...     print(f"Generated {len(result.files)} files")
        ... else:
        ...     for error in result.errors:
        ...         print(f"Error: {error}")

    Attributes:
        options: Compilation options dict
        verbose: Whether to print debug information
        target: Target language ('python' or 'cpp')
    """

    def __init__(self, options: Optional[Dict[str, Any]] = None):
        """Initialize the compiler pipeline.

        Args:
            options: Compilation options including:
                - target: 'python' or 'cpp' (default: 'python')
                - verbose: Print debug info
                - output_dir: Default output directory
        """
        self.options = options or {}
        self.verbose = self.options.get("verbose", False)
        self.target = self.options.get("target", "python")
        self.auto_build = self.options.get("auto_build", True)
        self.build_cache = self.options.get("build_cache", True)

    def compile_file(self, file_path: str) -> CompilationResult:
        """Compile a single NOS source file.

        Args:
            file_path: Path to a .node or .interface file

        Returns:
            CompilationResult with generated files or errors

        Example:
            >>> pipeline = CompilerPipeline({'verbose': True})
            >>> result = pipeline.compile_file('my_node.node')
            >>> print(f"Success: {result.success}")
            >>> print(f"Files generated: {list(result.files.keys())}")
        """
        path = Path(file_path)
        try:
            # utf-8-sig: tolerate a BOM written by Windows editors
            source = path.read_text(encoding="utf-8-sig")
        except FileNotFoundError:
            return CompilationResult(errors=[f"{file_path}: error: file not found"])
        except (OSError, UnicodeDecodeError) as e:
            return CompilationResult(errors=[f"{file_path}: error: cannot read file: {e}"])

        return self._compile(source, file_path)

    def compile_string(self, source: str, file_name: str = "<string>") -> CompilationResult:
        """Compile NOS source from a string.

        Args:
            source: NOS source code
            file_name: Name for error reporting

        Returns:
            CompilationResult with generated files or errors
        """
        return self._compile(source, file_name)

    def _compile(self, source: str, file_name: str) -> CompilationResult:
        """Parse, analyse and generate; shared by compile_file and compile_string."""
        result = CompilationResult()
        source = source.lstrip("\ufeff")

        if self.target != "python":
            result.errors.append(
                f"{file_name}: error: target '{self.target}' is not implemented yet " f"(only 'python' is supported)"
            )
            return result

        try:
            logger.info("Parsing: %s", file_name)
            ast = self._parse_string(source, file_name)
            result.ast = ast

            logger.info("Analyzing: %s", file_name)
            analysis = self._analyze(ast)
            result.errors.extend(str(e) for e in analysis.errors)
            result.warnings.extend(str(w) for w in analysis.warnings)
            if not analysis.is_valid:
                return result

            logger.info("Generating: %s", file_name)
            generated = self._generate(ast, analysis.symbol_table)
            result.files = generated.files

            if generated.security_errors:
                result.errors.extend(generated.security_errors)
                return result

            if not generated.files:
                result.errors.append(
                    f"{file_name}: error: nothing to generate " f"(the file declares no node or launch)"
                )
                return result

            result.package_name = ros_package_name(ast)
            if isinstance(ast, nodes.File) and ast.package:
                result.package_version = ast.package.version
            result.dependencies = package_dependencies(ast)
            result.success = True
            return result

        except NOSSyntaxError as e:
            result.ast = None
            result.errors.extend(e.errors)
            return result
        except Exception as e:  # a bug in the compiler, not in the user's source
            logger.debug("Internal compiler error", exc_info=True)
            result.errors.append(
                f"{file_name}: internal compiler error: {type(e).__name__}: {e} "
                f"(this is a bug in NOS; run with --verbose for the traceback)"
            )
            if self.verbose:
                result.errors.append(traceback.format_exc())
            return result

    def _parse_string(self, source: str, file_name: str) -> nodes.ASTNode:
        """Parse source string into AST using ANTLR4.

        Raises:
            NOSSyntaxError: the source is not valid NOS (messages are
                ``file:line:col: error: ...``)
        """
        input_stream = InputStream(source)

        error_listener = NOSErrorListener(file_name)
        lexer = NOSLexer(input_stream)
        lexer.removeErrorListeners()
        lexer.addErrorListener(error_listener)

        tokens = CommonTokenStream(lexer)

        parser = NOSParser(tokens)
        parser.removeErrorListeners()
        parser.addErrorListener(error_listener)

        parse_tree = parser.nosFile()

        if error_listener.errors:
            raise NOSSyntaxError(error_listener.errors)

        builder = ASTBuilder(file_name)
        ast = builder.visit(parse_tree)
        if builder.errors:
            raise NOSSyntaxError(builder.errors)
        if ast is None:
            raise NOSInternalError(f"AST builder returned nothing for {file_name}")

        return ast

    def _analyze(self, ast: nodes.ASTNode) -> AnalysisResult:
        """Run semantic analysis on AST."""
        analyzer = SemanticAnalyzer()
        return analyzer.analyze(ast)

    def _generate(self, ast: nodes.ASTNode, symbol_table: Any) -> GenerationOutput:
        """Generate target code from AST."""
        output = GenerationOutput()

        if self.target == "python":
            # Generate Python nodes
            node_gen = PythonGenerator(self.options)
            node_output = node_gen.generate(ast, symbol_table)
            output.files.update(node_output.files)

            if hasattr(node_output, "security_errors") and node_output.security_errors:
                output.security_errors = node_output.security_errors

            # Generate launch files
            launch_gen = LaunchTranspiler(self.options)
            launch_output = launch_gen.generate(ast, symbol_table)
            output.files.update(launch_output.files)

        return output

    def write_outputs(self, result: CompilationResult, output_dir: str) -> bool:
        """Write generated files as a colcon workspace under ``output_dir``.

        The package scaffold is derived from the files that are in the package
        directory after writing, so several inputs (written by one call to
        :meth:`CompilationResult.merge` or by separate runs) all keep their
        console-script entry points and launch files.

        Args:
            result: Compilation result with files
            output_dir: Target directory path

        Returns:
            True if everything was written (and built, unless auto_build is off).
            On failure the reason is appended to ``result.errors``.
        """
        if not result.success:
            return False

        output_path = Path(output_dir)

        try:
            output_path.mkdir(parents=True, exist_ok=True)
            workspace_path = output_path / "ros2_ws"
            package_name = result.package_name or self._extract_package_name(result.ast)
            package_root = workspace_path / "src" / package_name

            self._write_ros2_sources(package_root, package_name, result.files)
            self._generate_ros2_package_scaffold(package_root, package_name, result)
        except OSError as e:
            result.errors.append(f"error: cannot write output to {output_dir}: {e}")
            return False

        if not self.auto_build:
            return True

        fingerprint = self._compute_build_fingerprint(package_root, package_name)
        if self._should_run_build(workspace_path, package_name, fingerprint):
            try:
                self._run_colcon_build(workspace_path, package_name)
            except RuntimeError as e:
                result.errors.append(f"error: {e}")
                return False
            self._update_build_cache(workspace_path, package_name, fingerprint)
        else:
            logger.info("Build cache hit for package '%s', skipping colcon build", package_name)
        return True

    def _extract_package_name(self, ast: Optional[nodes.ASTNode]) -> str:
        """Extract a valid ROS2 package name from AST."""
        return ros_package_name(ast)

    def _compute_build_fingerprint(self, package_root: Path, package_name: str) -> str:
        """Hash of every file in the package directory, used by the build cache."""
        hasher = hashlib.sha256()
        hasher.update(package_name.encode("utf-8"))
        hasher.update(self.target.encode("utf-8"))

        for path in sorted(p for p in package_root.rglob("*") if p.is_file()):
            hasher.update(path.relative_to(package_root).as_posix().encode("utf-8"))
            hasher.update(path.read_bytes())

        return hasher.hexdigest()

    def _build_cache_file(self, workspace_path: Path) -> Path:
        """Return build cache file path."""
        return workspace_path / ".nos_build_cache.json"

    def _load_build_cache(self, workspace_path: Path) -> Dict[str, str]:
        """Load build cache dictionary from disk."""
        cache_file = self._build_cache_file(workspace_path)
        if not cache_file.exists():
            return {}
        try:
            return json.loads(cache_file.read_text(encoding="utf-8"))
        except Exception:
            return {}

    def _update_build_cache(self, workspace_path: Path, package_name: str, fingerprint: str) -> None:
        """Persist successful build fingerprint to cache."""
        cache = self._load_build_cache(workspace_path)
        cache[package_name] = fingerprint
        cache_file = self._build_cache_file(workspace_path)
        cache_file.write_text(json.dumps(cache, indent=2), encoding="utf-8")

    def _should_run_build(self, workspace_path: Path, package_name: str, fingerprint: str) -> bool:
        """Determine whether colcon build is required."""
        if not self.build_cache:
            return True

        cache = self._load_build_cache(workspace_path)
        cached = cache.get(package_name)
        install_package = workspace_path / "install" / package_name
        return cached != fingerprint or not install_package.exists()

    def _run_colcon_build(self, workspace_path: Path, package_name: str) -> None:
        """Run colcon build for a single package."""
        logger.info("Building ROS2 package '%s' with colcon", package_name)

        cmd = ["colcon", "build", "--packages-select", package_name]
        try:
            proc = subprocess.run(cmd, cwd=str(workspace_path), capture_output=True, text=True, check=False)
        except FileNotFoundError as exc:
            raise RuntimeError("colcon executable not found. Install ROS2/colcon or run with --no-build.") from exc

        if proc.returncode != 0:
            stderr = proc.stderr.strip()
            stdout = proc.stdout.strip()
            details = stderr or stdout or "Unknown colcon build failure"
            raise RuntimeError(f"colcon build failed for package '{package_name}': {details}")

        if proc.stdout:
            logger.debug(proc.stdout)

    def _generate_ros2_package_scaffold(self, package_root: Path, package_name: str, result: CompilationResult) -> None:
        """Generate ament_python package scaffolding for what is in the package directory."""
        package_module_dir = package_root / package_name
        launch_dir = package_root / "launch"
        resource_dir = package_root / "resource"

        for directory in (package_module_dir, launch_dir, resource_dir):
            directory.mkdir(parents=True, exist_ok=True)

        entry_points = [
            f"            '{path.stem} = {package_name}.{path.stem}:main',"
            for path in sorted(package_module_dir.glob("*_node.py"))
        ]
        entry_points_block = "\n".join(entry_points)

        launch_files = sorted(p.name for p in launch_dir.glob("*_launch.py"))
        launch_files_str = ", ".join(f"'launch/{name}'" for name in launch_files)

        version = result.package_version or "0.0.1"
        maintainer = self.options.get("maintainer", "NOS")
        maintainer_email = self.options.get("maintainer_email", "nos@local")

        # `depends:` plus the interface packages the nodes use are rosdep keys
        exec_depends = ["rclpy"] + [d for d in result.dependencies if d != "rclpy"]
        exec_depend_xml = "\n".join(f"  <exec_depend>{xml_escape(d)}</exec_depend>" for d in exec_depends)

        package_xml = f"""<?xml version="1.0"?>
<package format="3">
  <name>{package_name}</name>
  <version>{xml_escape(version)}</version>
  <description>Auto-generated from NOS</description>
  <maintainer email="{xml_escape(maintainer_email)}">{xml_escape(maintainer)}</maintainer>
  <license>Apache-2.0</license>

  <buildtool_depend>ament_python</buildtool_depend>

{exec_depend_xml}
  <!-- The generated nodes also import nos.runtime: install it with `pip install nos`
       (it is not a rosdep key, so it is declared in setup.py instead). -->

  <export>
    <build_type>ament_python</build_type>
  </export>
</package>
"""

        setup_cfg = """[develop]
script_dir=$base/lib/{package}
[install]
install_scripts=$base/lib/{package}
""".format(package=package_name)

        setup_py = f"""from setuptools import find_packages, setup

package_name = '{package_name}'

setup(
    name=package_name,
    version={version!r},
    packages=find_packages(exclude=['test']),
    data_files=[
        ('share/ament_index/resource_index/packages', ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
        ('share/' + package_name + '/launch', [{launch_files_str}]),
    ],
    install_requires=['setuptools', 'nos'],
    zip_safe=True,
    maintainer={maintainer!r},
    maintainer_email={maintainer_email!r},
    description='Auto-generated ROS2 package from NOS',
    license='Apache-2.0',
    tests_require=['pytest'],
    entry_points={{
        'console_scripts': [
{entry_points_block}
        ],
    }},
)
"""

        (package_root / "package.xml").write_text(package_xml, encoding="utf-8")
        (package_root / "setup.cfg").write_text(setup_cfg, encoding="utf-8")
        (package_root / "setup.py").write_text(setup_py, encoding="utf-8")
        (resource_dir / package_name).write_text("", encoding="utf-8")

        init_file = package_module_dir / "__init__.py"
        if not init_file.exists():
            init_file.write_text("", encoding="utf-8")

    def _write_ros2_sources(self, package_root: Path, package_name: str, files: Dict[str, str]) -> None:
        """Write generated Python and launch files into ROS2 package layout."""
        package_module_dir = package_root / package_name
        launch_dir = package_root / "launch"

        for file_path, content in files.items():
            rel_path = Path(file_path)
            if file_path.endswith("_launch.py"):
                target = launch_dir / rel_path.name
            else:
                target = package_module_dir / rel_path.name

            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            logger.info("Wrote: %s", target)

    def compile_multiple(self, file_paths: List[str]) -> Dict[str, CompilationResult]:
        """Compile multiple files and return results.

        Args:
            file_paths: List of source file paths

        Returns:
            Dictionary mapping file paths to compilation results
        """
        results = {}
        for path in file_paths:
            results[path] = self.compile_file(path)
        return results
